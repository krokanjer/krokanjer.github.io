function setupCarousels() {
	const videoViewport = document.querySelector('[data-carousel="video"]');
	const videoTrack = videoViewport ? videoViewport.querySelector('.video-carousel-track') : null;
	let videoSlides = videoTrack ? Array.from(videoTrack.querySelectorAll('.video-slide')) : [];
	const originalVideoSlideCount = videoSlides.length;
	let currentVideoIndex = 0;
	let wrapSnapTimeoutId = null;

	if (videoTrack && originalVideoSlideCount > 1) {
		const firstSlideClone = videoSlides[0].cloneNode(true);
		const lastSlideClone = videoSlides[originalVideoSlideCount - 1].cloneNode(true);

		firstSlideClone.classList.add('is-clone');
		lastSlideClone.classList.add('is-clone');
		firstSlideClone.setAttribute('aria-hidden', 'true');
		lastSlideClone.setAttribute('aria-hidden', 'true');

		videoTrack.insertBefore(lastSlideClone, videoSlides[0]);
		videoTrack.appendChild(firstSlideClone);
		videoSlides = Array.from(videoTrack.querySelectorAll('.video-slide'));
		currentVideoIndex = 1;
	}

	function updateVideoActiveState() {
		videoSlides.forEach((slide, index) => {
			const isClone = slide.classList.contains('is-clone');
			const isActive = index === currentVideoIndex;
			const canInteract = isActive && !isClone;
			slide.classList.toggle('is-active', isActive);
			slide.setAttribute('aria-hidden', String(!isActive));

			const iframe = slide.querySelector('iframe');
			if (iframe) {
				iframe.setAttribute('tabindex', canInteract ? '0' : '-1');
			}
		});
	}

	function updateVideoPosition(animate = true) {
		if (!videoViewport || !videoTrack || videoSlides.length === 0) {
			return;
		}

		updateVideoActiveState();

		const activeSlide = videoSlides[currentVideoIndex];
		const viewportWidth = videoViewport.clientWidth;
		const slideWidth = activeSlide.getBoundingClientRect().width;
		const centeredOffset = activeSlide.offsetLeft - (viewportWidth - slideWidth) / 2;

		if (!animate) {
			videoTrack.style.transition = 'none';
		}

		videoTrack.style.transform = `translateX(${-centeredOffset}px)`;

		if (!animate) {
			requestAnimationFrame(() => {
				videoTrack.style.transition = '';
			});
			return;
		}

		if (originalVideoSlideCount <= 1) {
			return;
		}
	}

	updateVideoPosition(false);
	window.addEventListener('resize', () => updateVideoPosition(false));

	function moveVideo(direction) {
		if (videoSlides.length <= 1) {
			return;
		}

		if (wrapSnapTimeoutId) {
			window.clearTimeout(wrapSnapTimeoutId);
			wrapSnapTimeoutId = null;
		}

		const isWrappingPrev = direction === 'prev' && currentVideoIndex === 1;
		const isWrappingNext = direction === 'next' && currentVideoIndex === originalVideoSlideCount;

		if (isWrappingPrev) {
			currentVideoIndex = 0;
			updateVideoPosition(true);
			wrapSnapTimeoutId = window.setTimeout(() => {
				currentVideoIndex = originalVideoSlideCount;
				updateVideoPosition(false);
				wrapSnapTimeoutId = null;
			}, 480);
			return;
		}

		if (isWrappingNext) {
			currentVideoIndex = videoSlides.length - 1;
			updateVideoPosition(true);
			wrapSnapTimeoutId = window.setTimeout(() => {
				currentVideoIndex = 1;
				updateVideoPosition(false);
				wrapSnapTimeoutId = null;
			}, 480);
			return;
		}

		if (direction === 'next') {
			currentVideoIndex += 1;
		} else {
			currentVideoIndex -= 1;
		}

		updateVideoPosition(true);
	}

	videoSlides.forEach((slide, index) => {
		slide.addEventListener('click', () => {
			if (index === currentVideoIndex) {
				return;
			}

			if (slide.classList.contains('is-clone')) {
				moveVideo(index === 0 ? 'prev' : 'next');
				return;
			}

			moveVideo(index < currentVideoIndex ? 'prev' : 'next');
		});
	});

	const buttons = document.querySelectorAll('.carousel-arrow');

	buttons.forEach((button) => {
		button.addEventListener('click', () => {
			const targetName = button.getAttribute('data-target');
			const direction = button.getAttribute('data-direction');

			if (targetName === 'video') {
				moveVideo(direction === 'prev' ? 'prev' : 'next');
				return;
			}

			const viewport = document.querySelector(`[data-carousel="${targetName}"]`);

			if (!viewport) {
				return;
			}

			const amount = Math.max(280, viewport.clientWidth * 0.78);
			viewport.scrollBy({ left: direction === 'next' ? amount : -amount, behavior: 'smooth' });
		});
	});
}

(function initProjectDetailPage() {
	const slug = getSlugFromPath();
	const project = ALL_PROJECTS.find((item) => item.slug === slug) || ALL_PROJECTS[0];
	renderPage(project);
	setupCarousels();
})();
